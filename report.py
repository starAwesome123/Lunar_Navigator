"""Collect every number you need for the README and the demo video.

Usage:
    python report.py
    python report.py --gnss 20=data/gnss_count20.csv 23.5=data/gnss_count.csv 26=data/gnss_count26.csv
Writes results.md (and prints it).
"""
import argparse
import os
import numpy as np
import pandas as pd
from metrics import load_site, site_metrics


def r1(d):
    """Round numeric values to 1 decimal (leave booleans alone)."""
    return {k: (round(float(v), 1) if isinstance(v, (float, np.floating)) else v) for k, v in d.items()}


def md_table(df, index_name="site"):
    cols = [index_name] + [str(c) for c in df.columns]
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for idx, row in df.iterrows():
        out.append("| " + " | ".join([str(idx)] + [str(v) for v in row.values]) + " |")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--gnss", nargs="*", default=[
        "20=data/gnss_count20.csv", "23.5=data/gnss_count.csv", "26=data/gnss_count26.csv"])
    ap.add_argument("--mission-days", type=int, default=6)
    a = ap.parse_args()

    sites = pd.read_csv("sites.csv")
    names = [n for n in sites.name if os.path.exists(f"data/horizons_{n}.csv")]
    gnss = {}
    for item in a.gnss:
        ang, path = item.split("=", 1)
        if os.path.exists(path):
            gnss[ang] = pd.read_csv(path, parse_dates=["time_utc"])
        else:
            print("NOTE: file not found, skipped:", path)
    main_key = "23.5" if "23.5" in gnss else (next(iter(gnss)) if gnss else None)

    d0 = load_site(names[0])
    L = [f"# Results (generated by report.py)\n",
         f"Window: {d0.time_utc.min()} to {d0.time_utc.max()} UTC, {len(d0)} hourly samples. "
         f"Mission length used: {a.mission_days} days.\n"]

    rows = {n: r1(site_metrics(load_site(n), gnss.get(main_key), a.mission_days)) for n in names}
    L += [f"## Site comparison (GNSS main-lobe cone = {main_key} deg)\n",
          md_table(pd.DataFrame(rows).T), ""]

    if gnss:
        s = []
        for ang, g in sorted(gnss.items(), key=lambda kv: float(kv[0])):
            s.append({"cone_deg": ang, "max_usable_sats": int(g.n_total.max()),
                      "mean_usable_sats": round(g.n_total.mean(), 2),
                      "hours_with_>=1_%": round(100 * (g.n_total >= 1).mean(), 1),
                      "hours_with_>=4_%": round(100 * (g.n_total >= 4).mean(), 1)})
        L += ["## GNSS sensitivity to the cone angle (all hours, Moon-centre receiver)\n",
              md_table(pd.DataFrame(s).set_index("cone_deg"), "cone_deg"), ""]
        for k in (">=1", ">=4"):
            col = f"earth_up_and_{k}_gnss_%"
            t = {}
            for ang, g in sorted(gnss.items(), key=lambda kv: float(kv[0])):
                t[ang] = {n: round(site_metrics(load_site(n), g, a.mission_days)[col], 1) for n in names}
            L += [f"## Earth up AND {k} GNSS satellite usable (% of hours), by cone angle\n",
                  md_table(pd.DataFrame(t).rename(columns=lambda c: f"{c} deg")), ""]
    text = "\n".join(L)
    open("results.md", "w").write(text)
    print(text)


if __name__ == "__main__":
    main()